@dataclass
class Point3D:
    id: int
    x: float
    y: float
    z: float


@dataclass
class Trajectory:
    id: int
    points: list[Point3D]


def load_points(path: str, key: str = "3d_point") -> list[Point3D]:
    """
    Load 3D points from a JSON annotations file.

    Returns list of 3D points skipping null / invalid entries.
    """

    with open(path, "r") as f:
        data = json.load(f)

    pts: list[Point3D] = []
    anns = data.get("annotations", [])
    for idx, ann in enumerate(anns):
        p = ann.get(key, None)
        if p is not None:
            pts.append(Point3D(id=idx, x=float(p[0]), y=float(p[1]), z=float(p[2])))
    return pts


def detect_trajectories(points, min_length=3, threshold=0.001) -> list[Trajectory]:
    """
    Detect trajectories by:
    1. Splitting at obstacles in X and Y
    2. Splitting at local minima in Z
    """
    if not points:
        return []

    xs = [p.x for p in points]
    ys = [p.y for p in points]
    zs = [p.z for p in points]

    # X and Y boundaries (walls)
    min_x = min(xs) + threshold
    max_x = max(xs) - threshold
    min_y = min(ys) + threshold
    max_y = max(ys) - threshold

    break_indices = {0}  # Use a set to avoid duplicate indices
    for i in range(1, len(points) - 1):
        # Condition for Xs (for walls)
        if xs[i] < min_x or xs[i] > max_x:
            break_indices.add(i)

        # Condition for Ys (for walls)
        if ys[i] < min_y or ys[i] > max_y:
            break_indices.add(i)

        # Local minima condition for Zs (for parabolic motion)
        if zs[i] < zs[i-1] and zs[i] < zs[i+1]:
            break_indices.add(i)

    break_indices.add(len(points) - 1)  # include last point
    sorted_breaks = sorted(list(break_indices))

    # Build trajectories
    trajectories: list[Trajectory] = []
    for start, end in zip(sorted_breaks, sorted_breaks[1:]):
        if end - start >= min_length:
            trajectories.append(Trajectory(id=len(trajectories), points=points[start:end+1]))

    return trajectories


def add_field_meshes(fig: go.Figure):
    x_coords = [0, 18, 18, 0]
    y_coords = [0, 0, 9, 9]
    z_coords = [0, 0, 0, 0]

    # Define the two triangles that form the rectangle
    #    The values in i, j, k are the indices of the vertices in x, y, z
    #    Triangle 1: vertices 0, 1, 2
    #    Triangle 2: vertices 0, 2, 3
    i_indices = [0, 0]
    j_indices = [1, 2]
    k_indices = [2, 3]

    # Create the Figure and the Mesh3d trace
    fig.add_trace(go.Mesh3d(
          x=x_coords,
          y=y_coords,
          z=z_coords,
          i=i_indices,
          j=j_indices,
          k=k_indices,
          color='lightblue',
          opacity=0.70,
          name='My Rectangle'
      )
    )

    fig.add_trace(go.Mesh3d(
        # Define the 4 vertices of the net
        x=[9, 9, 9, 9],
        y=[0, 9, 9, 0],
        z=[0, 0, 2.4, 2.4],

        # Define the 2 triangles that form the rectangle
        i=[0, 0],
        j=[1, 2],
        k=[2, 3],

        color='orange',
        opacity=0.50,
        name='Net'
    ))


def plot_trajectories_interactive(trajectories, plot_points=False, plot_markers=False):
    """
    Creates an interactive 3D plot of trajectories using Plotly.
    """
    fig = go.Figure()

    # Plot all points faintly for context
    if plot_points:
        all_pts = np.array([[p.x, p.y, p.z] for traj in trajectories for p in traj.points])
        fig.add_trace(go.Scatter3d(
            x=all_pts[:, 0], y=all_pts[:, 1], z=all_pts[:, 2],
            mode='markers',
            marker=dict(size=2, color='gray', opacity=0.15),
            name="All Points",
            hoverinfo='skip'  # Hide hover text for these points
        ))

    # Predefined 10 bright colors
    base_colors = [
        "#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd",
        "#8c564b", "#e377c2", "#7f7f7f", "#bcbd22", "#17becf"
    ]

    # To store annotations (labels)
    annotations = []

    # To plot markers in batches for a cleaner legend
    start_points = {'x': [], 'y': [], 'z': []}
    end_points = {'x': [], 'y': [], 'z': []}

    # Plot each trajectory with cycling colors
    for traj_id, traj in enumerate(trajectories):
        color = base_colors[traj_id % len(base_colors)]
        traj_pts = np.array([[p.x, p.y, p.z] for p in traj.points])

        # Add the trajectory line
        fig.add_trace(go.Scatter3d(
            x=traj_pts[:, 0], y=traj_pts[:, 1], z=traj_pts[:, 2],
            mode='lines',
            line=dict(color=color, width=5),
            name=f"Traj {traj_id}"
        ))

        # Collect start & end points
        if plot_markers:
            start_points['x'].append(traj_pts[0, 0])
            start_points['y'].append(traj_pts[0, 1])
            start_points['z'].append(traj_pts[0, 2])
            end_points['x'].append(traj_pts[-1, 0])
            end_points['y'].append(traj_pts[-1, 1])
            end_points['z'].append(traj_pts[-1, 2])

        # Add trajectory ID as a text annotation
        annotations.append(dict(
            showarrow=False,
            x=traj_pts[0, 0], y=traj_pts[0, 1], z=traj_pts[0, 2] - 0.2,
            text=f"<b>{traj_id}</b>",
            xanchor="center",
            font=dict(color=color, size=10)
        ))

    # Plot all start and end markers in two efficient traces
    if plot_markers and plot_start_end_points:
        fig.add_trace(go.Scatter3d(
            x=start_points['x'], y=start_points['y'], z=start_points['z'],
            mode='markers',
            marker=dict(color='green', size=5, symbol='circle'),
            name='Start Points'
        ))
        fig.add_trace(go.Scatter3d(
            x=end_points['x'], y=end_points['y'], z=end_points['z'],
            mode='markers',
            marker=dict(color='red', size=5, symbol='x'),
            name='End Points'
        ))

    add_field_meshes(fig)

    # Update the layout for a clean look
    fig.update_layout(
        title="Interactive 3D Ball Trajectories",
        scene=dict(
            xaxis_title="X",
            yaxis_title="Y",
            zaxis_title="Z",
            annotations=annotations,
            yaxis_range=[-6, 15],
            xaxis_range=[-6, 24],
            zaxis_range=[0, 6],
            aspectmode='manual',
            aspectratio=dict(x=2.1, y=1.3, z=0.6)
        ),
        margin=dict(l=0, r=0, b=0, t=40), # Reduce margins
        legend=dict(x=0.8, y=0.9),
    )

    fig.show()


