def predict_trajectory_from_fit(trajectory: Trajectory):
    """
    Fits a physically-based model (quadratic for Z, linear for X/Y) to the
    trajectory data and extrapolates it to the ground (z=0).

    Returns:
        A tuple containing:
        - smoothed_original: The (x,y,z) points of the original trajectory, smoothed by the fit.
        - predicted_path: The (x,y,z) points of the extrapolated path to the ground.
    """
    if len(trajectory.points) < 3:
        return None, None # Need at least 3 points for a stable quadratic fit

    # 1. Extract coordinates and create a time-like variable (frame index)
    points = np.array([[p.x, p.y, p.z] for p in trajectory.points])
    x, y, z = points[:, 0], points[:, 1], points[:, 2]
    frame_indices = np.arange(len(z))

    # 2. Fit polynomial models to the data
    # z(t) = at^2 + bt + c  (2nd degree polynomial)
    z_coeffs = np.polyfit(frame_indices, z, 2)
    z_fit_func = np.poly1d(z_coeffs)

    # x(t) = mt + c  (1st degree polynomial)
    x_coeffs = np.polyfit(frame_indices, x, 1)
    x_fit_func = np.poly1d(x_coeffs)

    # y(t) = mt + c  (1st degree polynomial)
    y_coeffs = np.polyfit(frame_indices, y, 1)
    y_fit_func = np.poly1d(y_coeffs)

    # 3. Generate the smoothed path for the original trajectory
    smoothed_x = x_fit_func(frame_indices)
    smoothed_y = y_fit_func(frame_indices)
    smoothed_z = z_fit_func(frame_indices)
    smoothed_original = np.vstack([smoothed_x, smoothed_y, smoothed_z]).T

    # 4. Find the frame index when the ball hits the ground (z=0)
    # The roots of the quadratic polynomial give the indices where z=0.
    roots = np.roots(z_coeffs)

    # We want the root that is in the future (greater than the last observed index)
    last_frame_index = frame_indices[-1]
    future_roots = roots[(roots.imag == 0) & (roots.real > last_frame_index)]

    if len(future_roots) == 0:
        return smoothed_original, None # No valid future impact point found

    ground_impact_index = future_roots.real.min()

    # 5. Generate the points for the predicted path
    prediction_indices = np.linspace(last_frame_index, ground_impact_index, 50)

    pred_x = x_fit_func(prediction_indices)
    pred_y = y_fit_func(prediction_indices)
    pred_z = z_fit_func(prediction_indices)

    # Ensure the path stops exactly at z=0
    pred_z[pred_z < 0] = 0

    predicted_path = np.vstack([pred_x, pred_y, pred_z]).T

    return smoothed_original, predicted_path, z_coeffs


def create_interactive_predictor(trajectories):
    """
    Creates an interactive Plotly plot with a dropdown and button to predict trajectories.
    """
    traj_dropdown = Dropdown(
        options=[(f"Trajectory {traj.id}", traj.id) for traj in trajectories],
        description='Select Trajectory:',
        value=0
    )

    def plot_prediction(trajectory_selection):
        fig = go.Figure()
        selected_id = traj_dropdown.value
        selected_traj = next((t for t in trajectories if t.id == selected_id), None)
        if not selected_traj: return

        # Use the new fitting function to get the paths
        smoothed_original, predicted_path, z_coeffs = predict_trajectory_from_fit(selected_traj)

        if z_coeffs is not None:
            a, b, c = z_coeffs
            equation_str = f"z(n) = {a:.4f}n²"
            equation_str += f" + {b:.4f}n" if b >= 0 else f" - {-b:.4f}n"
            equation_str += f" + {c:.4f}" if c >= 0 else f" - {-c:.4f}"

            print("-" * 40)
            print(f"Trajectory {traj.id} Parabola Equation:")
            print(equation_str)
            print("-" * 40)

        fig.data = [] # Clear previous plot data

        if smoothed_original is None:
            fig.update_layout(title=f"Could not fit Trajectory {selected_id} (not enough points)")
            return

        # Plot the original noisy data points for comparison
        raw_pts = np.array([[p.x, p.y, p.z] for p in selected_traj.points])
        fig.add_trace(go.Scatter3d(
            x=raw_pts[:, 0], y=raw_pts[:, 1], z=raw_pts[:, 2],
            mode='markers',
            marker=dict(color='grey', size=3, opacity=0.6),
            name='Observed Points'
        ))

        # Plot the smoothed, fitted trajectory line
        fig.add_trace(go.Scatter3d(
            x=smoothed_original[:, 0], y=smoothed_original[:, 1], z=smoothed_original[:, 2],
            mode='lines',
            line=dict(color='blue', width=6),
            name='Fitted Trajectory'
        ))

        # Plot the predicted path if it exists
        if predicted_path is not None:
            fig.add_trace(go.Scatter3d(
                x=predicted_path[:, 0], y=predicted_path[:, 1], z=predicted_path[:, 2],
                mode='lines',
                line=dict(color='red', width=6, dash='dash'),
                name='Predicted Path'
            ))
            fig.add_trace(go.Scatter3d(
                x=[predicted_path[-1, 0]], y=[predicted_path[-1, 1]], z=[predicted_path[-1, 2]],
                mode='markers',
                marker=dict(color='darkred', size=8, symbol='x'),
                name='Predicted Impact'
            ))

        add_field_meshes(fig)

        fig.update_layout(
            title=f"Trajectory {selected_id} with Fitted Prediction",
            scene=dict(xaxis_title="X", yaxis_title="Y", zaxis_title="Z"),
            legend=dict(x=0.8, y=0.9), width=1200, height=800, autosize=False,
            scene_yaxis_range=[-6, 15],
            scene_xaxis_range=[-6, 24],
            scene_zaxis_range=[0, 6],
            scene_aspectmode='manual',
            scene_aspectratio=dict(x=2.1, y=1.3, z=0.6)
        )
        fig.show()

    interactive_plot = interactive(plot_prediction, trajectory_selection=traj_dropdown)
    display(interactive_plot)


